const blocks = rawText.trim().split(/\n\n+/);
const questions = [];

for (let i = 0; i < blocks.length; i += 2) {
  const qBlock = blocks[i];
  const aBlock = blocks[i+1];
  if (!aBlock) break;

  const qLines = qBlock.split('\n');
  const qTextMatch = qLines[0].match(/^\d+\.\s*(.*)/);
  if (!qTextMatch) continue;
  const englishQuestion = qTextMatch[1].trim();

  let opts = qLines.slice(1);
  if (opts.length === 0) continue;

  const englishOptions = opts.map(o => o.replace(/^[A-D]\)\s*/, '').trim());
  while (englishOptions.length < 4) englishOptions.push('');

  const aMatch = aBlock.match(/Answer:\s*([A-D])/);
  let correctOptionIndex = 0;
  if (aMatch) {
     const letter = aMatch[1];
     if (letter === 'A') correctOptionIndex = 0;
     if (letter === 'B') correctOptionIndex = 1;
     if (letter === 'C') correctOptionIndex = 2;
     if (letter === 'D') correctOptionIndex = 3;
  }

  questions.push({
    englishQuestion,
    englishOptions,
    hindiQuestion: "",
    hindiOptions: ["", "", "", ""],
    hindiExplanation: "",
    correctOptionIndex,
    englishExplanation: "",
    subject: "Miscellaneous",
    difficulty: "medium"
  });
}

